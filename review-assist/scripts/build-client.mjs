import { realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { transformAsync } from "@babel/core";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const HOST_MODULES = [
  "@getpaseo/plugin",
  "@getpaseo/plugin/*",
  "@tanstack/react-query",
  "react",
  "react/jsx-runtime",
  "react-native",
  "zod",
];

export async function buildClient() {
  const result = await build({
    entryPoints: [join(root, "client", "index.tsx")],
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2020",
    jsx: "automatic",
    mainFields: ["module", "main"],
    external: HOST_MODULES,
    write: false,
    logLevel: "silent",
  });
  const lowered = await transformAsync(result.outputFiles[0].text, {
    babelrc: false,
    configFile: false,
    sourceType: "module",
    // Paseo's Android app evaluates the bundle on Hermes, which leaves `class` syntax unbound.
    plugins: ["@babel/plugin-transform-classes"],
  });
  if (lowered?.code == null) throw new Error("Babel produced no client bundle");
  return `// @ts-nocheck\n// Generated by scripts/build-client.mjs from client/index.tsx.\n${lowered.code}\n`;
}

if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "index.client.ts"), await buildClient());
}
