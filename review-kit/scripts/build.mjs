import { realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const HOST_MODULES = [
  "@getpaseo/plugin",
  "@getpaseo/plugin/*",
  "@tanstack/react-query",
  "react",
  "react/jsx-runtime",
  "react-native",
  "zod",
];

export async function buildClient(root) {
  const { build, transformAsync } = tools(root);
  const result = await build({
    entryPoints: [join(root, "client", "index.tsx")],
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2020",
    jsx: "automatic",
    mainFields: ["module", "main"],
    external: HOST_MODULES,
    preserveSymlinks: true,
    write: false,
    logLevel: "silent",
  });
  const lowered = await transformAsync(result.outputFiles[0].text, {
    babelrc: false,
    configFile: false,
    sourceType: "module",
    // Paseo's Android app evaluates the bundle on Hermes, which leaves `class` syntax unbound.
    plugins: ["@babel/plugin-transform-classes"],
  });
  if (lowered?.code == null) throw new Error("Babel produced no client bundle");
  return `// @ts-nocheck\n// Generated by kit/scripts/build.mjs from client/index.tsx.\n${lowered.code}\n`;
}

export async function buildServer(root) {
  const { build } = tools(root);
  const result = await build({
    entryPoints: [join(root, "server", "index.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    packages: "external",
    preserveSymlinks: true,
    write: false,
    logLevel: "silent",
  });
  return `// @ts-nocheck\n// Generated by kit/scripts/build.mjs from server/index.ts.\n${result.outputFiles[0].text}`;
}

// The kit has no node_modules of its own: build with the plugin's.
function tools(root) {
  const require = createRequire(join(root, "package.json"));
  return { build: require("esbuild").build, transformAsync: require("@babel/core").transformAsync };
}

if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  const target = process.argv[2];
  if (target === "client") writeFileSync(join(root, "index.client.ts"), await buildClient(root));
  else if (target === "server") writeFileSync(join(root, "index.server.ts"), await buildServer(root));
  else throw new Error(`Usage: build.mjs client|server, not ${target}`);
}
